function caveBat() {
  const art = pixelCanvas(64, 48, ['#292735', '#474052', '#695771', '#927a93', '#ba9fab', '#e5ccaf', '#be785e', '#edb86c']);
  const { shape, line, rect, dot } = art;
  // 折れた翼の骨と大きな耳。輪郭を太くせず、暗い紫の塊で見せる。
  for (const side of [-1, 1]) {
    const p = (x: number, y: number): readonly [number, number] => [32 + side * x, y];
    shape([p(6, 22), p(12, 10), p(25, 4), p(30, 9), p(26, 14), p(28, 27), p(20, 23), p(17, 33), p(10, 28)], '2', true);
    shape([p(11, 21), p(16, 13), p(26, 8), p(23, 15), p(24, 23), p(19, 19), p(15, 27)], '3');
    line(p(7, 24), p(25, 7), '4'); line(p(11, 22), p(21, 20), '1');
    shape([p(3, 17), p(7, 4), p(11, 2), p(10, 19)], '2', true);
    shape([p(6, 15), p(8, 7), p(9, 6), p(8, 17)], '6');
  }
  shape([[25, 19], [30, 16], [37, 18], [42, 24], [40, 33], [36, 39], [27, 39], [23, 32], [23, 24]], '2', true);
  shape([[26, 21], [30, 19], [32, 20], [29, 25], [26, 29]], '4');
  shape([[29, 31], [34, 29], [38, 32], [36, 36], [29, 36]], '3');
  rect(26, 25, 5, 3, '0'); rect(35, 25, 5, 3, '0'); dot(28, 26, '7'); dot(37, 26, '7');
  line([30, 31], [35, 31], '0'); rect(30, 32, 1, 3, '5'); rect(35, 32, 1, 3, '5');
  line([27, 39], [24, 42], '5'); line([36, 39], [39, 42], '5');
  return art.finish();
}

