import { pixelCanvas } from '../characters/pixel-canvas';

function arachne() {
  const art=pixelCanvas(64,56,['#251e30','#48304d','#71426b','#a75c85','#ce94b2','#e9c5d4','#303f37','#557655','#89aa68','#c6d18a','#5c4a54','#87707e','#b1a0ad','#ddced4','#e4be63','#f4e3a1']);
  const {shape,rect,line,dot}=art;
  // 八本の脚を胴体から離し、各関節に一段の照り返しを置く。
  for(const side of [-1,1]) for(let leg=0;leg<4;leg++) {
    const base=32+side*12, end=32+side*(25-leg*2), y=19+leg*6;
    shape([[base,y],[end,y-8],[end+side*3,y-5],[end+side*4,y+10],[end,y+13],[end-side*3,y],[base,y+5]],'1',true);
    line([base,y+1],[end,y-5],'3'); line([end+side*2,y-3],[end+side*3,y+9],'2');
  }
  shape([[24,8],[40,8],[46,17],[45,30],[38,38],[26,38],[19,31],[18,18]],'2',true);
  shape([[25,10],[39,10],[43,19],[40,27],[23,27],[21,19]],'3');
  for(const [x,y] of [[26,13],[32,12],[38,13],[24,20],[30,19],[36,19],[41,20],[32,26]]) {rect(x-1,y,3,3,'0');dot(x,y,'8');dot(x,y+1,'9');}
  shape([[25,30],[39,30],[43,36],[41,43],[35,47],[27,46],[21,39]],'1',true);
  rect(24,35,15,5,'2');rect(26,36,3,3,'8');rect(35,36,3,3,'8');
  shape([[25,40],[29,41],[26,48],[23,47]],'d',true); shape([[36,41],[40,40],[41,47],[38,49]],'c',true);
  line([24,42],[25,46],'5'); line([39,42],[39,46],'5'); dot(26,49,'8'); dot(40,51,'8');
  return art.finish();
}

