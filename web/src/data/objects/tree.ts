import type { PixelSprite } from './types';

const width = 48, height = 48;
const pixels = Array.from({ length: height }, () => Array<string>(width).fill('.'));
const palette = [
  '#344532', '#405636', '#52703d', '#6b8a49', '#84a258', '#a3b86b',
  '#453a2c', '#715437', '#967048', '#b48d5b',
];
function rect(x: number, y: number, w: number, h: number, color: string): void {
  for (let row = y; row < y + h; row++) for (let col = x; col < x + w; col++) pixels[row][col] = color;
}
function shape(points: readonly (readonly [number, number])[], color: string): void {
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    let inside = false;
    for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
      const [ax, ay] = points[i], [bx, by] = points[j];
      if ((ay > y + 0.5) !== (by > y + 0.5) && x + 0.5 < (bx - ax) * (y + 0.5 - ay) / (by - ay) + ax) inside = !inside;
    }
    if (inside) pixels[y][x] = color;
  }
}

